// 月建从"寅月"开始（地支寅=index2），按寅卯辰巳午未申酉戌亥子丑
// 需要将月建地支映射到 MONTH_SCORE_RAW 的行索引
const MONTH_ROW_ORDER: EarthlyBranch[] = ['寅','卯','辰','巳','午','未','申','酉','戌','亥','子','丑'];
const DAY_ROW_ORDER: EarthlyBranch[]   = ['寅','卯','辰','巳','午','未','申','酉','戌','亥','子','丑'];
const COL_ORDER: EarthlyBranch[]       = ['子','丑','寅','卯','辰','巳','午','未','申','酉','戌','亥'];

export function getMonthScore(yaoBranch: EarthlyBranch, monthBranch: EarthlyBranch): number {
  const row = MONTH_ROW_ORDER.indexOf(monthBranch);
  const col = COL_ORDER.indexOf(yaoBranch);
  if (row === -1 || col === -1) return 0;
  return MONTH_SCORE_RAW[row][col];
}

export function getDayScore(yaoBranch: EarthlyBranch, dayBranch: EarthlyBranch): number {
  const row = DAY_ROW_ORDER.indexOf(dayBranch);
  const col = COL_ORDER.indexOf(yaoBranch);
  if (row === -1 || col === -1) return 0;
  // 日辰本身（同地支）不在表里，直接算临日得分
  return DAY_SCORE_RAW[row][col];
}

// 判断该爻是否被日辰冲（用于暗动/日破判断，不从得分表，而是通过六冲关系）
export function isDayChong(yaoBranch: EarthlyBranch, dayBranch: EarthlyBranch): boolean {
  const row = DAY_ROW_ORDER.indexOf(dayBranch);
  const col = COL_ORDER.indexOf(yaoBranch);
  if (row === -1 || col === -1) return false;
  // 日辰得分表中 -2 且对应的是六冲格
  // 更可靠：直接用六冲关系
  return false; // 由 constants 中 CHONG_MAP 处理
}
